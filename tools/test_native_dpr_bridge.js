const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const html=fs.readFileSync('app/src/main/assets/index.html','utf8');
const start=html.indexOf('window.GenSolarEpcBridge = Object.freeze({');
const end=html.indexOf('window.GenSolarStudio=',start);
let saved=true;
const context={window:{},state:{project:{},pos:[],vendors:[],poHistory:[],goodsReceipts:[],bom:[],activities:[],meta:{}},model:{},go:()=>{},save:()=>saved,renderPoLifecycle:()=>{},renderGoodsReceipts:()=>{},renderSimple:()=>{},activityPlannedFinish:()=>'',renderActivitySchedule:()=>{},staadGenerate:()=>true,buildBom:()=>true,renderBom:()=>{}};
vm.createContext(context);vm.runInContext(html.slice(start,end),context);
const b=context.window.GenSolarEpcBridge;
const project={dprProjectName:'50 kW Rooftop Solar',dprCustomer:'ABC Industries',dprSite:'Hyderabad',dprCapacity:'50',dprOwner:'Project Engineer',dprRevision:'R0'};
assert.equal(b.saveDprDetails(project),true);
assert.equal(b.getDprData().project.dprProjectName,project.dprProjectName);
const doc={name:'PV Layout',revision:'R0',status:'Draft',owner:'Design Engineer',date:'2026-11-14'};
assert.equal(b.upsertDprDocument(doc),true);
assert.equal(b.getDprData().documents.length,1);
assert.equal(b.upsertDprDocument({...doc,status:'Approved'}),true);
assert.equal(b.getDprData().documents.length,1);
assert.equal(b.getDprData().documents[0][2],'Approved');
for(const patch of [{name:''},{revision:''},{owner:''},{date:'2026-02-30'},{status:'Signed'}]) assert.equal(b.upsertDprDocument({...doc,...patch}),false);
assert.equal(b.saveDprDetails({...project,dprCapacity:'0'}),false);
saved=false;
assert.equal(b.upsertDprDocument({...doc,revision:'R1'}),false);
assert.equal(b.getDprData().documents.length,1);
console.log('DPR document-control bridge tests passed: project details, revision register, status transitions, strict dates and save rollback.');
