const assert = require("node:assert/strict");
const fs = require("node:fs");
const source = fs.readFileSync("app/src/main/assets/index.html", "utf8");
const start = source.indexOf("function validateSimpleRoofPolygon(");
const end = source.indexOf("\nfunction validateImportedCadLayout", start);
assert.ok(start >= 0 && end > start, "roof polygon validation functions must exist");
const validatorSource = source.slice(start, end);
const validate = new Function(validatorSource + ";return validateImportedRoofZones;")();
const base = {id:"R1",name:"Main roof",type:"RCC",elevation:5,pitch:0};
const valid = validate([{...base,vertices:[{x:0,y:0},{x:10,y:0},{x:10,y:8},{x:0,y:8}]}]);
assert.equal(valid.length,1);
assert.equal(valid[0].vertices.length,4);
const concave = validate([{...base,vertices:[{x:0,y:0},{x:8,y:0},{x:8,y:3},{x:4,y:3},{x:4,y:8},{x:0,y:8}]}]);
assert.equal(concave.length,1,"simple concave roof polygons remain valid");
assert.throws(()=>validate([{...base,vertices:[{x:0,y:0},{x:4,y:4},{x:0,y:4},{x:3,y:0}]}]),/self-intersects or overlaps/,"self-crossing roof boundary must be rejected");
assert.throws(()=>validate([{...base,vertices:[{x:0,y:0},{x:4,y:0},{x:4,y:0},{x:0,y:4}]}]),/zero-length or duplicate consecutive edge/,"duplicate adjacent points must be rejected");
assert.throws(()=>validate([{...base,vertices:[{x:0,y:0},{x:6,y:0},{x:6,y:4},{x:3,y:0},{x:0,y:4}]}]),/self-intersects or overlaps/,"non-adjacent edge contact or overlap must be rejected");
assert.throws(()=>validate([{...base,vertices:[{x:0,y:0},{x:10,y:0},{x:10,y:10},{x:0,y:10},{x:0,y:0}]}]),/zero-length or duplicate consecutive edge/,"explicit repeated closing point must be rejected rather than double-counted");
assert.throws(()=>validate([{...base,id:"R1",vertices:[{x:0,y:0},{x:1,y:0},{x:0,y:1}]},{...base,id:"R1",vertices:[{x:2,y:2},{x:3,y:2},{x:2,y:3}]}]),/unique/,"duplicate roof zone IDs remain invalid");
console.log("Roof polygon validation passed: convex/concave boundaries accepted; self-intersections, overlaps and duplicate edges rejected.");
