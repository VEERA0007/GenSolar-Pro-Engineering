const assert=require("node:assert/strict");
const fs=require("node:fs");
const source=fs.readFileSync("app/src/main/assets/index.html","utf8");
const bridge=source.indexOf("window.gensolarProjectState=state;");
const studio=source.indexOf("const state=window.gensolarProjectState;");
const model=source.indexOf("const model={version:1");
assert.ok(bridge>=0,"EPC project state must be published for the CAD studio");
assert.ok(studio>bridge&&studio<model,"CAD studio must bind to the shared EPC project state before initialising");
assert.ok(source.includes("if(!state)throw new Error('GenSolar EPC project state bridge is unavailable.');"),"Missing explicit bridge failure guard");
console.log("Shared EPC/CAD project-state bridge test passed.");
