const assert=require("node:assert/strict");
const fs=require("node:fs");
const source=fs.readFileSync("app/src/main/assets/index.html","utf8");
const start=source.indexOf("function dxf(){",200000);
const end=source.indexOf("\n$('cadExportDxf').onclick",start);
assert.ok(start>=0&&end>start,"CAD studio DXF exporter must exist");
const fn=source.slice(start,end).trim();
const rectCorners=(x,y,w,h)=>[{x,y},{x:x+w,y},{x:x+w,y:y+h},{x,y:y+h}];
const model={entities:[{type:"line",layer:"CABLE_ROUTE",a:{x:1,y:2},b:{x:3,y:4}}],layout:[{x:5,y:6,w:2,h:1}]};
const state={roofZones:[{id:"Z1",name:"Main roof",elevation:6.25,pitch:12.5,vertices:[{x:0,y:0},{x:20,y:0},{x:20,y:10},{x:0,y:10}]}]};
const output=new Function("model","state","rectCorners",fn+";return dxf();")(model,state,rectCorners);
const pairs=output.split("\r\n");
assert.ok(pairs.includes("4"),"DXF INSUNITS must declare millimetres for coordinates scaled by 1000");
assert.ok(output.includes("ROOF_ZONES"),"Surveyed roof boundaries must be exported on their own layer");
assert.ok(output.includes("ROOF_ZONE_LABELS"),"Roof-zone labels must be exported");
assert.ok(output.includes("EL 6.25 m"),"Roof elevation must be preserved in the drawing label");
assert.ok(output.includes("PITCH 12.5 deg"),"Roof pitch must be preserved in the drawing label");
assert.ok(output.includes("CABLE_ROUTE"),"Editable CAD entities must be exported");
assert.ok(output.includes("PV_MODULES"),"PV module placements must be exported");
assert.ok(output.endsWith("0\r\nEOF"),"DXF must terminate with EOF");
const noZones=new Function("model","state","rectCorners",fn+";return dxf();")({...model,layout:[]},{roofZones:[]},rectCorners);
assert.ok(noZones.includes("CABLE_ROUTE"),"CAD drawings without a PV layout must still export");
console.log("CAD DXF unit, roof-zone, label, entity and PV export tests passed.");
